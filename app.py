# ----------------- ВКЛАДКА 1: Поиск по одной компании -----------------
with tab1:
    st.subheader("Поиск информации по конкретному клиенту или конкуренту")
    selected_company = st.selectbox(
        "Выберите компанию из списка:", df["Компания"].unique()
    )

    row = df[df["Компания"] == selected_company].iloc[0]

    col1, col2, col3 = st.st_columns(3)
    with col1:
        st.metric("Тип / Холдинг", row["Холдинг/Тип"])
        st.metric("Регион", row["Регион"])
    with col2:
        st.metric("Ответственный менеджер", row["Менеджер"])
        st.metric("Базовый домен", row["Домен"])

    st.markdown("---")
    st.write("### 🔗 Быстрые ссылки для мониторинга:")

    g_link = make_google_pdf_link(row["Домен"], row["Компания"])
    y_link = make_yandex_link(row["Компания"])

    c1, c2, c3 = st.columns(3)
    with c1:
        st.link_button(f"🔍 Искать сайт/PDF в Google ({target_year})", g_link)
    with c2:
        st.link_button(f"🟡 Искать в Яндекс", y_link)
    with c3:
        if row["Alt"] != "-":
            st.link_button("📌 Альтернативный канал / VK", row["Alt"])
        else:
            st.info("Альтернативных соцсетей не требуется")

# ----------------- ВКЛАДКА 2: Поиск по менеджеру -----------------
