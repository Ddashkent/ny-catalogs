# Функция генерации УМНЫХ ссылок
def make_google_pdf_link(domain, comp_name):
    if domain != "-":
        query = f"site:{domain} новогодние подарки каталог {target_year}"
    else:
        query = f"{comp_name} новогодние подарки каталог {target_year}"
    return f"https://www.google.com/search?q={urllib.parse.quote(query)}"


def make_yandex_link(comp_name):
    query = f"{comp_name} новогодние подарки каталог {target_year} pdf"
    return f"https://yandex.ru/search/?text={urllib.parse.quote(query)}"


